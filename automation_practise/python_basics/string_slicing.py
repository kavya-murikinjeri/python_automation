# syn = [start:end:step] - end value is excluded
# slicing is useful when we need to certain parts or range of a string
para = "This is python basics module"
print(para[0:3])
print(para[:])
print(para[3:])
print(para[:6])
print(para[0:8:2])
print(para[0:-1])
print(para[::-1]) # -- reversing a string
