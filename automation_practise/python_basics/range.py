# range() is a biult in function in Python is used to generate a sequence of numbers. It is commonly used in for loops.
'''
   range(start, stop, step)
   start (optional): The starting number (default is 0).
stop (required): The sequence stops before this number.
step (optional): The increment/decrement (default is 1).
'''
for i in range(10):
    print(i)

print("using start, end and step")
for j in range(1,10,2):
    print(j)
